CREATE TABLE IF NOT EXISTS invoices (
  id CHAR(36) NOT NULL,
  tenantId VARCHAR(191) NOT NULL,
  siteId VARCHAR(191) NULL,
  customerId VARCHAR(191) NULL,
  invoiceNumber VARCHAR(64) NOT NULL,
  orderId VARCHAR(191) NULL,
  externalOrderId VARCHAR(191) NULL,
  source ENUM('WOOCOMMERCE', 'CUSTOM', 'MANUAL') NOT NULL DEFAULT 'CUSTOM',
  status ENUM('DRAFT', 'ISSUED', 'UNPAID', 'PARTIALLY_PAID', 'PAID', 'VOID', 'REFUNDED') NOT NULL DEFAULT 'ISSUED',
  currency CHAR(3) NOT NULL DEFAULT 'IRR',
  subtotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  discountTotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  taxTotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  shippingTotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  grandTotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  paidTotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  items JSON NOT NULL,
  sellerSnapshot JSON NOT NULL,
  buyerSnapshot JSON NOT NULL,
  notes TEXT NULL,
  issuedAt DATETIME NULL,
  paidAt DATETIME NULL,
  pdfStorageKey VARCHAR(512) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY invoices_tenant_invoice_number_unique (tenantId, invoiceNumber),
  KEY invoices_tenant_created_at_idx (tenantId, createdAt),
  KEY invoices_tenant_customer_idx (tenantId, customerId),
  KEY invoices_tenant_site_idx (tenantId, siteId),
  KEY invoices_tenant_status_idx (tenantId, status),
  KEY invoices_tenant_order_idx (tenantId, orderId),
  KEY invoices_tenant_external_order_idx (tenantId, externalOrderId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
